/**
 * 简历 PII 掩码（F1 · D2）—— 发送到 AI 之前的**代码层**脱敏。
 *
 * 为什么放在代码层而不是只写提示词：简历含真实姓名 / 手机 / 邮箱 / 身份证 /
 * 生日 / 主页，一旦离开本机就收不回来。提示词约束是「软」的（模型可以不乖），
 * 本模块是「硬」的（可单测、可复现），两者叠加而非互相替代。
 *
 * ⚠️ 诚实边界：**中文姓名无法用正则可靠识别**（同音字、无标记、任意位置都可能
 * 出现）。因此 UI 告知文案不得写「已匿名化」，只能写「已掩码联系方式；姓名由
 * 模型侧约束不输出」。本模块只承诺掩码**结构化标识**。
 *
 * 顺序敏感：URL → 邮箱 → 身份证 → 手机 → 固话 → 日期 → 姓名标注。
 * 身份证（18 位）内部含 11 位「1[3-9]…」子串，若先跑手机规则会把身份证截成
 * 半个手机号；URL 里也可能内嵌数字串，故最先整体替换为 `[link]`。
 */

/** 邮箱：`a.b@x.com` → `a***@x.com`（保留首字符与域名）。 */
const RE_EMAIL = /([A-Za-z0-9._%+-])[A-Za-z0-9._%+-]*@([A-Za-z0-9.-]+\.[A-Za-z]{2,})/g;
/** 身份证：17 位数字 + 校验位（数字或 X）→ 保留前 2 后 2。 */
const RE_ID = /\b(\d{2})\d{14}(\d[\dXx])\b/g;
/** 手机：1[3-9] + 9 位 → 保留前 3 后 4。 */
const RE_MOBILE = /\b(1[3-9]\d)\d{4}(\d{4})\b/g;
/** 固话：(0xx)xxxxxxx / 0xx-xxxxxxx / 0xx xxxxxxx → 保留区号。 */
const RE_TEL = /(\(\s?0\d{2,3}\s?\)|0\d{2,3})[\s-]?\d{7,8}/g;
/** 精确日期：1990年3月12日 / 1990-03-12 / 1990.3.12 → 只保留年份。 */
const RE_DATE = /(\d{4})\s*[年\-./]\s*\d{1,2}\s*[月\-./]\s*\d{1,2}\s*日?/g;
/** 主页 / 作品集链接 → [link]。 */
const RE_URL = /(?:https?:\/\/|www\.)[^\s，。；)）]+/gi;
/** 「姓名：张三」/「Name: Zhang San」→ 值掩码，标签保留（便于模型理解结构）。 */
const RE_NAME = /((?:姓名|名字|Name)\s*[:：]\s*)([A-Za-z\u4e00-\u9fa5·]{1,20}(?:\s+[A-Za-z\u4e00-\u9fa5·]{1,20})?)/gi;

/**
 * 掩码简历文本中的结构化个人标识（纯函数，不抛错、不联网）。
 * 非字符串引用一律按空串处理，绝不因怪输入崩掉导入链路。
 */
export function maskPii(text: string): string {
  if (typeof text !== "string" || text.length === 0) return "";
  return text
    .replace(RE_URL, "[link]")
    .replace(RE_EMAIL, "$1***@$2")
    .replace(RE_ID, "$1****$2")
    .replace(RE_MOBILE, "$1****$2")
    .replace(RE_TEL, "$1****")
    .replace(RE_DATE, "$1年")
    .replace(RE_NAME, "$1**");
}
